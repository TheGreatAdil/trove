//! The `.trv` project format. One project is one board.
//!
//! A `.trv` file is a zip archive:
//!
//! ```text
//! project.json      the board's items and their metadata (written by the frontend)
//! images/<id>.<ext> every image the board references, in its original format
//! ```
//!
//! While a project is open its images live unpacked in a session directory
//! (`<session>/images/`), so the webview can show them straight from disk.
//! Saving packs that directory back into a `.trv`.
//!
//! Version 1 files held several boards; they still open, as one board.

use std::collections::hash_map::DefaultHasher;
use std::collections::HashSet;
use std::fs::{self, File};
use std::hash::{Hash, Hasher};
use std::io::{self, Read, Write};
use std::path::{Path, PathBuf};
use std::time::UNIX_EPOCH;

use serde::Serialize;
use serde_json::Value;
use zip::write::SimpleFileOptions;
use zip::{CompressionMethod, ZipArchive, ZipWriter};

pub const EXTENSION: &str = "trv";
const FORMAT: &str = "trove";
const VERSION: u64 = 2;
const MANIFEST: &str = "project.json";
const IMAGES: &str = "images";

pub fn images_dir(session: &Path) -> PathBuf {
    session.join(IMAGES)
}

pub fn has_extension(path: &Path) -> bool {
    path.extension()
        .and_then(|e| e.to_str())
        .is_some_and(|e| e.eq_ignore_ascii_case(EXTENSION))
}

/// Image file names are generated by the app: `<id>.<ext>` using only ASCII
/// letters, digits, `-` and `_`. Anything else is rejected, which also rules
/// out path traversal from a crafted project file.
pub fn is_safe_name(name: &str) -> bool {
    let Some((stem, ext)) = name.rsplit_once('.') else {
        return false;
    };
    !stem.is_empty()
        && stem.len() <= 64
        && stem.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
        && (1..=5).contains(&ext.len())
        && ext.chars().all(|c| c.is_ascii_alphanumeric())
}

fn check_manifest(manifest: &Value) -> Result<(), String> {
    if manifest.get("format").and_then(Value::as_str) != Some(FORMAT) {
        return Err("This isn't a Trove project file.".into());
    }
    match manifest.get("version").and_then(Value::as_u64) {
        Some(v) if v <= VERSION => Ok(()),
        Some(_) => Err("This project was saved by a newer version of Trove.".into()),
        None => Err("This project file is damaged: it has no version.".into()),
    }
}

/// Unique, valid image file names referenced by the manifest's items.
fn referenced_images(manifest: &Value) -> Vec<String> {
    let mut seen = HashSet::new();
    manifest
        .get("items")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|item| item.get("file").and_then(Value::as_str))
        .filter(|name| is_safe_name(name) && seen.insert(name.to_string()))
        .map(String::from)
        .collect()
}

/// Packs `manifest` and the images it references from `session` into a `.trv`
/// at `dest`. Writes to a temporary file first and renames it over `dest`, so
/// a failed save never leaves a half-written project behind.
///
/// Returns how many referenced images were missing from the session (they are
/// skipped rather than failing the whole save).
pub fn write(dest: &Path, manifest: &Value, session: &Path) -> Result<usize, String> {
    check_manifest(manifest)?;
    let mut tmp = dest.as_os_str().to_owned();
    tmp.push(".tmp");
    let tmp = PathBuf::from(tmp);

    let result = write_zip(&tmp, manifest, session);
    match result {
        Ok(missing) => fs::rename(&tmp, dest)
            .map(|_| missing)
            .map_err(|e| format!("Couldn't save the project: {e}")),
        Err(e) => {
            let _ = fs::remove_file(&tmp);
            Err(format!("Couldn't save the project: {e}"))
        }
    }
}

fn write_zip(path: &Path, manifest: &Value, session: &Path) -> zip::result::ZipResult<usize> {
    let mut zip = ZipWriter::new(File::create(path)?);
    let deflated = SimpleFileOptions::default().compression_method(CompressionMethod::Deflated);
    // Images are already compressed; storing them keeps saves fast.
    let stored = SimpleFileOptions::default()
        .compression_method(CompressionMethod::Stored)
        .large_file(true);

    zip.start_file(MANIFEST, deflated)?;
    let json = serde_json::to_vec_pretty(manifest).map_err(io::Error::from)?;
    zip.write_all(&json)?;

    let mut missing = 0;
    for name in referenced_images(manifest) {
        let mut image = match File::open(images_dir(session).join(&name)) {
            Ok(file) => file,
            Err(e) if e.kind() == io::ErrorKind::NotFound => {
                missing += 1;
                continue;
            }
            Err(e) => return Err(e.into()),
        };
        zip.start_file(format!("{IMAGES}/{name}"), stored)?;
        io::copy(&mut image, &mut zip)?;
    }

    zip.finish()?.sync_all()?;
    Ok(missing)
}

/// Unpacks the `.trv` at `src` into `session` and returns its manifest.
pub fn extract(src: &Path, session: &Path) -> Result<Value, String> {
    let file = File::open(src).map_err(|e| match e.kind() {
        io::ErrorKind::NotFound => "That project file no longer exists.".to_string(),
        _ => format!("Couldn't open the project: {e}"),
    })?;
    let mut zip = ZipArchive::new(file).map_err(|_| "This isn't a Trove project file.".to_string())?;
    let images = images_dir(session);
    fs::create_dir_all(&images).map_err(|e| format!("Couldn't open the project: {e}"))?;

    let damaged = |e: &dyn std::fmt::Display| format!("This project file is damaged: {e}");
    let mut manifest = None;
    for i in 0..zip.len() {
        let mut entry = zip.by_index(i).map_err(|e| damaged(&e))?;
        if entry.is_dir() {
            continue;
        }
        let name = entry.name().map_err(|e| damaged(&e))?.into_owned();
        if name == MANIFEST {
            let mut json = String::new();
            entry.read_to_string(&mut json).map_err(|e| damaged(&e))?;
            manifest = Some(serde_json::from_str::<Value>(&json).map_err(|e| damaged(&e))?);
        } else if let Some(image) = name.strip_prefix("images/") {
            if !is_safe_name(image) {
                continue;
            }
            let mut out = File::create(images.join(image)).map_err(|e| format!("Couldn't open the project: {e}"))?;
            io::copy(&mut entry, &mut out).map_err(|e| damaged(&e))?;
        }
    }

    let manifest = manifest.ok_or_else(|| damaged(&"project.json is missing"))?;
    check_manifest(&manifest)?;
    Ok(manifest)
}

fn read_manifest_from<R: Read + io::Seek>(zip: &mut ZipArchive<R>) -> Result<Value, String> {
    let damaged = |e: &dyn std::fmt::Display| format!("This project file is damaged: {e}");
    let mut entry = zip.by_name(MANIFEST).map_err(|_| damaged(&"project.json is missing"))?;
    let mut json = String::new();
    entry.read_to_string(&mut json).map_err(|e| damaged(&e))?;
    let manifest = serde_json::from_str::<Value>(&json).map_err(|e| damaged(&e))?;
    check_manifest(&manifest)?;
    Ok(manifest)
}

fn open_zip(path: &Path) -> Result<ZipArchive<File>, String> {
    let file = File::open(path).map_err(|e| match e.kind() {
        io::ErrorKind::NotFound => "That project file no longer exists.".to_string(),
        _ => format!("Couldn't open the project: {e}"),
    })?;
    ZipArchive::new(file).map_err(|_| "This isn't a Trove project file.".to_string())
}

/// Edits a saved `.trv` without opening it: `edit` changes the manifest, images
/// it now references are copied from the archive itself or from
/// `<add_from>/images/`, and images nothing references any more are dropped.
pub fn update(path: &Path, add_from: &Path, edit: impl FnOnce(&mut Value)) -> Result<(), String> {
    let mut src = open_zip(path)?;
    let mut manifest = read_manifest_from(&mut src)?;
    edit(&mut manifest);
    manifest["version"] = Value::from(VERSION);

    let mut tmp = path.as_os_str().to_owned();
    tmp.push(".tmp");
    let tmp = PathBuf::from(tmp);
    let result = (|| -> zip::result::ZipResult<()> {
        let mut out = ZipWriter::new(File::create(&tmp)?);
        let deflated = SimpleFileOptions::default().compression_method(CompressionMethod::Deflated);
        let stored = SimpleFileOptions::default()
            .compression_method(CompressionMethod::Stored)
            .large_file(true);
        out.start_file(MANIFEST, deflated)?;
        out.write_all(&serde_json::to_vec_pretty(&manifest).map_err(io::Error::from)?)?;
        for name in referenced_images(&manifest) {
            let entry_name = format!("{IMAGES}/{name}");
            if let Ok(entry) = src.by_name(&entry_name) {
                out.raw_copy_file(entry)?;
            } else if let Ok(mut image) = File::open(images_dir(add_from).join(&name)) {
                out.start_file(entry_name, stored)?;
                io::copy(&mut image, &mut out)?;
            }
        }
        out.finish()?.sync_all()?;
        Ok(())
    })();
    drop(src);
    match result {
        Ok(()) => fs::rename(&tmp, path).map_err(|e| format!("Couldn't update the board: {e}")),
        Err(e) => {
            let _ = fs::remove_file(&tmp);
            Err(format!("Couldn't update the board: {e}"))
        }
    }
}

/// What the sidebar shows for a board file, read without opening the board.
#[derive(Serialize, Debug, Default)]
#[serde(rename_all = "camelCase")]
pub struct Info {
    pub path: String,
    /// The board's name from project.json; the sidebar falls back to the file name.
    pub name: Option<String>,
    pub count: usize,
    pub updated_at: f64,
    /// An image from the board, unpacked into the thumbnail cache.
    pub thumb: Option<String>,
    pub color: Option<String>,
    pub error: Option<String>,
}

/// The name a board carries inside its file, if it has one.
pub fn board_name(manifest: &Value) -> Option<String> {
    let name = manifest.get("name")?.as_str()?.split_whitespace().collect::<Vec<_>>().join(" ");
    (!name.is_empty()).then(|| name.chars().take(200).collect())
}

fn sort_key(item: &Value) -> f64 {
    item.get("pos").or_else(|| item.get("createdAt")).and_then(Value::as_f64).unwrap_or(0.0)
}

pub fn info(path: &Path, thumbs: &Path) -> Info {
    let mut out = Info { path: path.display().to_string(), ..Default::default() };
    let mtime = fs::metadata(path)
        .and_then(|m| m.modified())
        .ok()
        .and_then(|t| t.duration_since(UNIX_EPOCH).ok())
        .map(|d| d.as_millis() as f64);
    let result = (|| -> Result<(), String> {
        let mut zip = open_zip(path)?;
        let manifest = read_manifest_from(&mut zip)?;
        out.name = board_name(&manifest);
        let items = manifest.get("items").and_then(Value::as_array).cloned().unwrap_or_default();
        out.count = items.len();
        out.updated_at = ["updatedAt", "savedAt"]
            .iter()
            .find_map(|k| manifest.get(*k).and_then(Value::as_f64))
            .or(mtime)
            .unwrap_or(0.0);
        // The cover is the board's first image, in board order (newest first).
        let cover = items
            .iter()
            .filter(|i| i.get("file").and_then(Value::as_str).is_some_and(is_safe_name))
            .max_by(|a, b| sort_key(a).total_cmp(&sort_key(b)));
        if let Some(cover) = cover {
            out.color = cover.get("color").and_then(Value::as_str).map(String::from);
            let name = cover["file"].as_str().unwrap_or_default();
            let mut hasher = DefaultHasher::new();
            (path, mtime.unwrap_or(0.0).to_bits(), name).hash(&mut hasher);
            let ext = name.rsplit_once('.').map(|(_, e)| e).unwrap_or("img");
            let dest = thumbs.join(format!("{:016x}.{ext}", hasher.finish()));
            if !dest.exists() {
                fs::create_dir_all(thumbs).map_err(|e| e.to_string())?;
                let mut entry = zip.by_name(&format!("{IMAGES}/{name}")).map_err(|e| e.to_string())?;
                let mut file = File::create(&dest).map_err(|e| e.to_string())?;
                io::copy(&mut entry, &mut file).map_err(|e| e.to_string())?;
            }
            out.thumb = Some(dest.display().to_string());
        }
        Ok(())
    })();
    if let Err(e) = result {
        out.error = Some(e);
        out.updated_at = mtime.unwrap_or(0.0);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn temp_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("trove-test-{}-{name}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn safe_names() {
        assert!(is_safe_name("abc123.png"));
        assert!(is_safe_name("a-b_c.jpeg"));
        assert!(!is_safe_name("../evil.png"));
        assert!(!is_safe_name("a/b.png"));
        assert!(!is_safe_name("a\\b.png"));
        assert!(!is_safe_name("noext"));
        assert!(!is_safe_name(".png"));
        assert!(!is_safe_name("a.toolong"));
    }

    #[test]
    fn extension_check_ignores_case() {
        assert!(has_extension(Path::new("C:/x/My Board.trv")));
        assert!(has_extension(Path::new("a.TRV")));
        assert!(!has_extension(Path::new("a.zip")));
        assert!(!has_extension(Path::new("trv")));
    }

    #[test]
    fn round_trip() {
        let root = temp_dir("round-trip");
        let session = root.join("a");
        fs::create_dir_all(images_dir(&session)).unwrap();
        fs::write(images_dir(&session).join("one.png"), b"png-bytes").unwrap();
        fs::write(images_dir(&session).join("unused.jpg"), b"not saved").unwrap();

        let manifest = json!({
            "format": "trove",
            "version": 1,
            "boards": [{ "id": "b1", "name": "Board" }],
            "items": [
                { "id": "one", "boardId": "b1", "file": "one.png" },
                { "id": "dup", "boardId": "b1", "file": "one.png" },
                { "id": "gone", "boardId": "b1", "file": "gone.png" },
                { "id": "bad", "boardId": "b1", "file": "../evil.png" },
                { "id": "web", "boardId": "b1", "src": "https://example.com/x.jpg" }
            ]
        });
        let dest = root.join("project.trv");
        let missing = write(&dest, &manifest, &session).unwrap();
        assert_eq!(missing, 1);
        assert!(!root.join("project.trv.tmp").exists());

        let opened = root.join("b");
        let read_back = extract(&dest, &opened).unwrap();
        assert_eq!(read_back, manifest);
        assert_eq!(fs::read(images_dir(&opened).join("one.png")).unwrap(), b"png-bytes");
        assert!(!images_dir(&opened).join("unused.jpg").exists());

        // Saving over an existing project replaces it.
        let manifest2 = json!({ "format": "trove", "version": 1, "boards": [], "items": [] });
        write(&dest, &manifest2, &session).unwrap();
        assert_eq!(extract(&dest, &root.join("c")).unwrap(), manifest2);

        fs::remove_dir_all(&root).unwrap();
    }

    #[test]
    fn rejects_foreign_files() {
        let root = temp_dir("foreign");
        let not_zip = root.join("x.trv");
        fs::write(&not_zip, b"hello").unwrap();
        assert!(extract(&not_zip, &root.join("s")).unwrap_err().contains("isn't a Trove project"));

        let wrong = json!({ "format": "other", "version": 1 });
        assert!(write(&root.join("y.trv"), &wrong, &root).is_err());

        let newer = json!({ "format": "trove", "version": 99 });
        assert!(write(&root.join("z.trv"), &newer, &root).unwrap_err().contains("newer version"));

        assert!(extract(&root.join("missing.trv"), &root.join("s")).unwrap_err().contains("no longer exists"));
        fs::remove_dir_all(&root).unwrap();
    }

    #[test]
    fn update_moves_items_between_saved_boards() {
        let root = temp_dir("update");
        let session = root.join("open");
        fs::create_dir_all(images_dir(&session)).unwrap();
        fs::write(images_dir(&session).join("a.png"), b"aaa").unwrap();
        fs::write(images_dir(&session).join("b.jpg"), b"bbb").unwrap();
        let board = root.join("Other.trv");
        let manifest = json!({ "format": "trove", "version": 2, "name": "  Portfolio   site ", "items": [
            { "id": "a", "file": "a.png", "pos": 1, "color": "rgb(1, 2, 3)" }
        ]});
        write(&board, &manifest, &session).unwrap();

        // Add an image and a note that only exist in the open session.
        update(&board, &session, |m| {
            let items = m["items"].as_array_mut().unwrap();
            items.push(json!({ "id": "b", "file": "b.jpg", "pos": 5 }));
            items.push(json!({ "id": "t", "kind": "text", "text": "hello", "pos": 3 }));
        })
        .unwrap();
        let out = root.join("check1");
        let m = extract(&board, &out).unwrap();
        assert_eq!(m["items"].as_array().unwrap().len(), 3);
        assert_eq!(fs::read(images_dir(&out).join("a.png")).unwrap(), b"aaa");
        assert_eq!(fs::read(images_dir(&out).join("b.jpg")).unwrap(), b"bbb");

        // Removing an item drops its image from the archive.
        update(&board, &session, |m| {
            m["items"].as_array_mut().unwrap().retain(|i| i["id"] != "b");
        })
        .unwrap();
        let out = root.join("check2");
        extract(&board, &out).unwrap();
        assert!(!images_dir(&out).join("b.jpg").exists());
        assert!(images_dir(&out).join("a.png").exists());

        // The sidebar summary: count, and the newest image as the cover.
        let thumbs = root.join("thumbs");
        let summary = info(&board, &thumbs);
        assert_eq!(summary.error, None);
        assert_eq!(summary.count, 2);
        assert_eq!(fs::read(summary.thumb.unwrap()).unwrap(), b"aaa");
        assert_eq!(summary.color.as_deref(), Some("rgb(1, 2, 3)"));
        // The board's own name survives edits and is independent of the file name.
        assert_eq!(summary.name.as_deref(), Some("Portfolio site"));
        assert_eq!(board_name(&json!({ "name": "   " })), None);
        assert_eq!(board_name(&json!({})), None);
        assert!(info(&root.join("nope.trv"), &thumbs).error.unwrap().contains("no longer exists"));

        fs::remove_dir_all(&root).unwrap();
    }
}
