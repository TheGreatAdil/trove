//! The `.trv` project format.
//!
//! A `.trv` file is a zip archive:
//!
//! ```text
//! project.json      boards, items and their metadata (written by the frontend)
//! images/<id>.<ext> every image the project references, in its original format
//! ```
//!
//! While a project is open its images live unpacked in a session directory
//! (`<session>/images/`), so the webview can show them straight from disk.
//! Saving packs that directory back into a `.trv`.

use std::collections::HashSet;
use std::fs::{self, File};
use std::io::{self, Read, Write};
use std::path::{Path, PathBuf};

use serde_json::Value;
use zip::write::SimpleFileOptions;
use zip::{CompressionMethod, ZipArchive, ZipWriter};

pub const EXTENSION: &str = "trv";
const FORMAT: &str = "trove";
const VERSION: u64 = 1;
const MANIFEST: &str = "project.json";
const IMAGES: &str = "images";

pub fn images_dir(session: &Path) -> PathBuf {
    session.join(IMAGES)
}

pub fn has_extension(path: &Path) -> bool {
    path.extension()
        .and_then(|e| e.to_str())
        .is_some_and(|e| e.eq_ignore_ascii_case(EXTENSION))
}

/// Image file names are generated by the app: `<id>.<ext>` using only ASCII
/// letters, digits, `-` and `_`. Anything else is rejected, which also rules
/// out path traversal from a crafted project file.
pub fn is_safe_name(name: &str) -> bool {
    let Some((stem, ext)) = name.rsplit_once('.') else {
        return false;
    };
    !stem.is_empty()
        && stem.len() <= 64
        && stem.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
        && (1..=5).contains(&ext.len())
        && ext.chars().all(|c| c.is_ascii_alphanumeric())
}

fn check_manifest(manifest: &Value) -> Result<(), String> {
    if manifest.get("format").and_then(Value::as_str) != Some(FORMAT) {
        return Err("This isn't a Trove project file.".into());
    }
    match manifest.get("version").and_then(Value::as_u64) {
        Some(v) if v <= VERSION => Ok(()),
        Some(_) => Err("This project was saved by a newer version of Trove.".into()),
        None => Err("This project file is damaged: it has no version.".into()),
    }
}

/// Unique, valid image file names referenced by the manifest's items.
fn referenced_images(manifest: &Value) -> Vec<String> {
    let mut seen = HashSet::new();
    manifest
        .get("items")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|item| item.get("file").and_then(Value::as_str))
        .filter(|name| is_safe_name(name) && seen.insert(name.to_string()))
        .map(String::from)
        .collect()
}

/// Packs `manifest` and the images it references from `session` into a `.trv`
/// at `dest`. Writes to a temporary file first and renames it over `dest`, so
/// a failed save never leaves a half-written project behind.
///
/// Returns how many referenced images were missing from the session (they are
/// skipped rather than failing the whole save).
pub fn write(dest: &Path, manifest: &Value, session: &Path) -> Result<usize, String> {
    check_manifest(manifest)?;
    let mut tmp = dest.as_os_str().to_owned();
    tmp.push(".tmp");
    let tmp = PathBuf::from(tmp);

    let result = write_zip(&tmp, manifest, session);
    match result {
        Ok(missing) => fs::rename(&tmp, dest)
            .map(|_| missing)
            .map_err(|e| format!("Couldn't save the project: {e}")),
        Err(e) => {
            let _ = fs::remove_file(&tmp);
            Err(format!("Couldn't save the project: {e}"))
        }
    }
}

fn write_zip(path: &Path, manifest: &Value, session: &Path) -> zip::result::ZipResult<usize> {
    let mut zip = ZipWriter::new(File::create(path)?);
    let deflated = SimpleFileOptions::default().compression_method(CompressionMethod::Deflated);
    // Images are already compressed; storing them keeps saves fast.
    let stored = SimpleFileOptions::default()
        .compression_method(CompressionMethod::Stored)
        .large_file(true);

    zip.start_file(MANIFEST, deflated)?;
    let json = serde_json::to_vec_pretty(manifest).map_err(io::Error::from)?;
    zip.write_all(&json)?;

    let mut missing = 0;
    for name in referenced_images(manifest) {
        let mut image = match File::open(images_dir(session).join(&name)) {
            Ok(file) => file,
            Err(e) if e.kind() == io::ErrorKind::NotFound => {
                missing += 1;
                continue;
            }
            Err(e) => return Err(e.into()),
        };
        zip.start_file(format!("{IMAGES}/{name}"), stored)?;
        io::copy(&mut image, &mut zip)?;
    }

    zip.finish()?.sync_all()?;
    Ok(missing)
}

/// Unpacks the `.trv` at `src` into `session` and returns its manifest.
pub fn extract(src: &Path, session: &Path) -> Result<Value, String> {
    let file = File::open(src).map_err(|e| match e.kind() {
        io::ErrorKind::NotFound => "That project file no longer exists.".to_string(),
        _ => format!("Couldn't open the project: {e}"),
    })?;
    let mut zip = ZipArchive::new(file).map_err(|_| "This isn't a Trove project file.".to_string())?;
    let images = images_dir(session);
    fs::create_dir_all(&images).map_err(|e| format!("Couldn't open the project: {e}"))?;

    let damaged = |e: &dyn std::fmt::Display| format!("This project file is damaged: {e}");
    let mut manifest = None;
    for i in 0..zip.len() {
        let mut entry = zip.by_index(i).map_err(|e| damaged(&e))?;
        if entry.is_dir() {
            continue;
        }
        let name = entry.name().map_err(|e| damaged(&e))?.into_owned();
        if name == MANIFEST {
            let mut json = String::new();
            entry.read_to_string(&mut json).map_err(|e| damaged(&e))?;
            manifest = Some(serde_json::from_str::<Value>(&json).map_err(|e| damaged(&e))?);
        } else if let Some(image) = name.strip_prefix("images/") {
            if !is_safe_name(image) {
                continue;
            }
            let mut out = File::create(images.join(image)).map_err(|e| format!("Couldn't open the project: {e}"))?;
            io::copy(&mut entry, &mut out).map_err(|e| damaged(&e))?;
        }
    }

    let manifest = manifest.ok_or_else(|| damaged(&"project.json is missing"))?;
    check_manifest(&manifest)?;
    Ok(manifest)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn temp_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("trove-test-{}-{name}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn safe_names() {
        assert!(is_safe_name("abc123.png"));
        assert!(is_safe_name("a-b_c.jpeg"));
        assert!(!is_safe_name("../evil.png"));
        assert!(!is_safe_name("a/b.png"));
        assert!(!is_safe_name("a\\b.png"));
        assert!(!is_safe_name("noext"));
        assert!(!is_safe_name(".png"));
        assert!(!is_safe_name("a.toolong"));
    }

    #[test]
    fn extension_check_ignores_case() {
        assert!(has_extension(Path::new("C:/x/My Board.trv")));
        assert!(has_extension(Path::new("a.TRV")));
        assert!(!has_extension(Path::new("a.zip")));
        assert!(!has_extension(Path::new("trv")));
    }

    #[test]
    fn round_trip() {
        let root = temp_dir("round-trip");
        let session = root.join("a");
        fs::create_dir_all(images_dir(&session)).unwrap();
        fs::write(images_dir(&session).join("one.png"), b"png-bytes").unwrap();
        fs::write(images_dir(&session).join("unused.jpg"), b"not saved").unwrap();

        let manifest = json!({
            "format": "trove",
            "version": 1,
            "boards": [{ "id": "b1", "name": "Board" }],
            "items": [
                { "id": "one", "boardId": "b1", "file": "one.png" },
                { "id": "dup", "boardId": "b1", "file": "one.png" },
                { "id": "gone", "boardId": "b1", "file": "gone.png" },
                { "id": "bad", "boardId": "b1", "file": "../evil.png" },
                { "id": "web", "boardId": "b1", "src": "https://example.com/x.jpg" }
            ]
        });
        let dest = root.join("project.trv");
        let missing = write(&dest, &manifest, &session).unwrap();
        assert_eq!(missing, 1);
        assert!(!root.join("project.trv.tmp").exists());

        let opened = root.join("b");
        let read_back = extract(&dest, &opened).unwrap();
        assert_eq!(read_back, manifest);
        assert_eq!(fs::read(images_dir(&opened).join("one.png")).unwrap(), b"png-bytes");
        assert!(!images_dir(&opened).join("unused.jpg").exists());

        // Saving over an existing project replaces it.
        let manifest2 = json!({ "format": "trove", "version": 1, "boards": [], "items": [] });
        write(&dest, &manifest2, &session).unwrap();
        assert_eq!(extract(&dest, &root.join("c")).unwrap(), manifest2);

        fs::remove_dir_all(&root).unwrap();
    }

    #[test]
    fn rejects_foreign_files() {
        let root = temp_dir("foreign");
        let not_zip = root.join("x.trv");
        fs::write(&not_zip, b"hello").unwrap();
        assert!(extract(&not_zip, &root.join("s")).unwrap_err().contains("isn't a Trove project"));

        let wrong = json!({ "format": "other", "version": 1 });
        assert!(write(&root.join("y.trv"), &wrong, &root).is_err());

        let newer = json!({ "format": "trove", "version": 99 });
        assert!(write(&root.join("z.trv"), &newer, &root).unwrap_err().contains("newer version"));

        assert!(extract(&root.join("missing.trv"), &root.join("s")).unwrap_err().contains("no longer exists"));
        fs::remove_dir_all(&root).unwrap();
    }
}
